def slug(title):
    return title.lower().replace(" ", "-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True)
    ap.add_argument("--code-dataset", default=None, help="default: <user>/ppg2ecg-bench-code")
    ap.add_argument("--capnobase-dataset", default=None)
    ap.add_argument("--aurora-dataset", default=None)
    ap.add_argument("--extra-raw", nargs="*", default=[], help="other raw datasets for k00 (e.g. manual BIDMC/DaLiA/WESAD)")
    a = ap.parse_args()
    code_ds = a.code_dataset or f"{a.user}/ppg2ecg-bench-code"
    raw = [d for d in (a.capnobase_dataset, a.aurora_dataset) if d] + a.extra_raw
    root = Path(__file__).resolve().parent / "kernels"
    if root.exists():  # remove folders of jobs that no longer exist (e.g. old k20/k21/k30/k31/k40)
        import shutil
        keep = {slug(t) for _, t, *_ in KERNELS}
        for d in root.iterdir():
            if d.is_dir() and d.name not in keep:
                shutil.rmtree(d)
                print(f"removed old job folder {d.name}")
    h = code_hash()
    root.mkdir(parents=True, exist_ok=True)
    (root / "EXPECTED_HASH").write_text(h)
    for stage, title, gpu, k00, k01, needs_raw in KERNELS:
        d = root / slug(title)
        d.mkdir(parents=True, exist_ok=True)
        (d / "run.py").write_text(BOOT.replace("{stage}", stage).replace("{hash}", h))
        meta = {
            "id": f"{a.user}/{slug(title)}",
            "title": title,
            "code_file": "run.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": "true",
            "enable_gpu": "true" if gpu else "false",
            "enable_internet": "true",
            "machine_shape": "NvidiaTeslaT4" if gpu else "",
            "dataset_sources": [code_ds] + (a.extra_raw if stage in RAW_STAGES else raw if needs_raw else []),
            "competition_sources": [],
            "kernel_sources": ([f"{a.user}/{slug(KERNELS[0][1])}"] if k00 else [])
                              + ([f"{a.user}/{slug(KERNELS[1][1])}"] if k01 else [])
                              + [f"{a.user}/{slug(t)}" for s2, t, *_ in KERNELS if s2 in EXTRA.get(stage, [])],
            "model_sources": [],
        }
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
        print(f"{d.relative_to(root.parent.parent)}  gpu={gpu}  inputs={meta['dataset_sources'] + meta['kernel_sources']}")


if __name__ == "__main__":
    main()
